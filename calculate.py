# Addition
def addition(a, b):
    return a + b

# Subtraction
def subtraction(a, b):
    return a - b

# Division
def division(a, b):
    return a / b

# Multiplication
def multiplication(a, b):
    return a * b

# Floor Division
def floor_division(a, b):
    return a // b

# Modulus
def modulus(a, b):
    return a % b

# Exponentiation
def exponentiation(a, b):
    return a ** b